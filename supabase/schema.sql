-- O/L Maths Progress database starter.
-- Run this in Supabase SQL Editor. Configure the first admin account manually as described in SETUP.md.

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  full_name text not null,
  role text not null default 'student' check (role in ('admin','student')),
  created_at timestamptz not null default now()
);

create table if not exists public.papers (
  id bigint generated by default as identity primary key,
  paper_name text not null,
  paper_date date not null,
  paper_type text not null default 'Full paper',
  total_marks numeric(7,2) not null check (total_marks > 0),
  created_by uuid references auth.users(id),
  created_at timestamptz not null default now()
);

create table if not exists public.marks (
  id bigint generated by default as identity primary key,
  student_id uuid not null references public.profiles(id) on delete cascade,
  paper_id bigint not null references public.papers(id) on delete cascade,
  obtained_marks numeric(7,2) not null check (obtained_marks >= 0),
  created_by uuid references auth.users(id),
  created_at timestamptz not null default now(),
  unique(student_id,paper_id)
);

create or replace function public.is_admin()
returns boolean language sql stable security definer set search_path = public
as $$ select exists(select 1 from public.profiles where id = auth.uid() and role = 'admin'); $$;

alter table public.profiles enable row level security;
alter table public.papers enable row level security;
alter table public.marks enable row level security;

drop policy if exists "profiles read self or admin" on public.profiles;
create policy "profiles read self or admin" on public.profiles
for select to authenticated using (id = auth.uid() or public.is_admin());

drop policy if exists "admin manage profiles" on public.profiles;
create policy "admin manage profiles" on public.profiles
for all to authenticated using (public.is_admin()) with check (public.is_admin());

drop policy if exists "students read own marks admin all" on public.marks;
create policy "students read own marks admin all" on public.marks
for select to authenticated using (student_id = auth.uid() or public.is_admin());

drop policy if exists "admin manage marks" on public.marks;
create policy "admin manage marks" on public.marks
for all to authenticated using (public.is_admin()) with check (public.is_admin());

drop policy if exists "authenticated read papers" on public.papers;
create policy "authenticated read papers" on public.papers
for select to authenticated using (true);

drop policy if exists "admin manage papers" on public.papers;
create policy "admin manage papers" on public.papers
for all to authenticated using (public.is_admin()) with check (public.is_admin());

-- Public leaderboard deliberately returns aggregate scores and full names only.
-- This is public data: publish it only after obtaining appropriate consent.
create or replace function public.get_public_leaderboard()
returns table (
  student_id uuid,
  full_name text,
  total_obtained numeric,
  total_possible numeric,
  paper_count bigint
)
language sql stable security definer set search_path = public
as $$
  select p.id, p.full_name,
         coalesce(sum(m.obtained_marks),0)::numeric,
         coalesce(sum(pa.total_marks),0)::numeric,
         count(m.id)
  from public.profiles p
  left join public.marks m on m.student_id = p.id
  left join public.papers pa on pa.id = m.paper_id
  where p.role = 'student'
  group by p.id,p.full_name
  order by coalesce(sum(m.obtained_marks),0) desc;
$$;

grant execute on function public.get_public_leaderboard() to anon, authenticated;
